interface PixelIconProps {
  name: PixelIconName;
  size?: number;
  color?: string;
}

const PixelIcon = ({ name, size = 24, color = '#1A2238' }: PixelIconProps) => {
  const matrix = ICONS[name];
  const cell = size / GRID;

  return (
    <View style={{ width: size, height: size }}>
      {matrix.map((row, y) => (
        <View key={y} style={{ flexDirection: 'row' }}>
          {row.split('').map((ch, x) => (
            <View
              key={x}
              style={{
                width: cell,
                height: cell,
                backgroundColor: ch === '#' ? color : 'transparent',
              }}
            />
          ))}
        </View>
      ))}
    </View>
  );
};

